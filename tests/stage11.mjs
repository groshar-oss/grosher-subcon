// בדיקת ניווט (חבילה 16): תפריט צד כללי וקצר, לשוניות הפרויקט בתוך הדף, מעבר פרויקט ו"+ פרויקט חדש"
import { chromium } from 'playwright';
const BASE = 'http://localhost:8123/'; const KEY = 'grosher-subcon-demo-v5'; const OUT = 'tests/shots/';
const b = await chromium.launch(); const p = await b.newPage({ viewport: { width: 1440, height: 900 } });
const errs = []; p.on('pageerror', e => errs.push(e.message)); p.on('console', m => { if (m.type() === 'error') errs.push(m.text()); });
const T = () => p.evaluate(k => JSON.parse(localStorage.getItem(k)).tables, KEY);
const ok = (name, cond) => { console.log((cond ? 'ok   ' : 'FAIL ') + name); if (!cond) process.exitCode = 1; };
await p.goto(BASE); await p.waitForSelector('.kpis');
await p.evaluate(() => { localStorage.clear(); }); await p.reload(); await p.waitForSelector('.kpis');
let t = await T(); const pr = t.projects.filter(x => x.tenant_id === t.tenants[0].id); const p1 = pr.find(x => x.name.includes('הרצליה')).id, p2 = pr.find(x => x.name.includes('בת ים')).id;
ok('no project section in side menu', await p.locator('.side .pnav, .side #psel').count() === 0);
ok('admin collapsed', await p.locator('.nadm').count() === 1 && !(await p.$eval('.nadm', d => d.open)));
ok('side menu fits one screen (no scroll)', await p.$eval('#side', s => s.scrollHeight <= s.clientHeight + 1));
ok('home has new project button', await p.locator('#hnew').isVisible());
await p.goto(BASE + `#/project/${p1}/control`); await p.waitForSelector('.ptabs');
ok('project tabs inside the page on desktop', await p.locator('.ptabs').isVisible() && await p.locator('.ptabs a').count() === 13);
ok('project selector in page header', await p.$eval('.phead #psel', s => s.value) === p1);
ok('projects highlighted in side menu', (await p.textContent('.side .nav a.on')).includes('פרויקטים'));
ok('control tab is on', (await p.textContent('.ptabs a.on')).includes('בקרה'));
ok('quota badge on tab', await p.locator('.ptabs a[href$="/quota"] .badge').count() === 1);
await p.screenshot({ path: OUT + 'nav-project.png' });
await p.click('.ptabs a[href$="/vo"]'); await p.waitForTimeout(400);
await p.selectOption('#psel', p2); await p.waitForTimeout(500);
ok('switch project keeps the same tab', (await p.evaluate(() => location.hash)) === `#/project/${p2}/vo`);
await p.click('.phead a[href="#/projects/new"]'); await p.waitForSelector('.ov'); await p.waitForTimeout(200);
ok('new project dialog opens from project header', (await p.textContent('.ov')).includes('פרויקט חדש') && (await p.evaluate(() => location.hash)) === '#/projects');
await p.keyboard.press('Escape'); await p.waitForTimeout(200);
await p.goto(BASE + '#/'); await p.waitForSelector('#hnew'); await p.click('#hnew'); await p.waitForSelector('.ov');
ok('new project dialog opens from home', (await p.textContent('.ov')).includes('סוג פרויקט'));
await p.keyboard.press('Escape');
await p.goto(BASE + '#/settings'); await p.waitForSelector('#democ');
ok('admin group opens on its pages', await p.$eval('.nadm', d => d.open));
await p.goto(BASE + `#/project/${p1}/day`); await p.waitForTimeout(500);
ok('work day page has no broken header', !(errs.length));
// טלפון
await p.setViewportSize({ width: 390, height: 844 });
await p.goto(BASE + `#/project/${p1}/control`); await p.waitForSelector('.ptabs'); await p.waitForTimeout(300);
ok('phone keeps top tabs', await p.locator('.ptabs').isVisible());
ok('phone no sideways scroll in project', await p.evaluate(() => document.documentElement.scrollWidth <= 392));
ok('phone google dot in top bar', await p.locator('.mobile-top .gdot').isVisible());
await p.click('#mnav'); await p.waitForTimeout(300); await p.screenshot({ path: OUT + 'm-menu.png' });
ok('phone drawer shows google status', await p.locator('.side #gpill').isVisible());
console.log(errs.length ? 'errors: ' + errs.join(' | ') : 'no errors');
if (errs.length) process.exitCode = 1;
await b.close();
